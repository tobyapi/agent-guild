//! アプリが解釈する通知要求。道具の利用可否と独立なので全バックエンド共通。
use super::PromptContext;

pub(super) fn section(ctx: &PromptContext<'_>) -> String {
    if !crate::agent::role_can_notify(&ctx.agent.tags) {
        return String::new();
    }
    r#"## デスクトップ通知
- 完了報告や人間の判断待ちなど、注意を促す必要があるときだけ、最終返答の末尾に次の専用ブロックで通知を要求できます。
```notify
確認してほしい短い内容
```
- フェンスは左端に正確に書き、前に人間向けの返答と空行を必ず書きます。通知本文はプレーンテキスト1行、160文字以内。1返答1件です。tasksブロックとは共存できます。
- skill-usage フッタも求められている場合は、notify ブロックの後に skill-usage フッタを書きます。
- 通常文・途中投稿・引用・他のコードブロックの中では通知しません。使い方の説明は引用か、4本以上のバッククォートのコードブロックに入れてください。
- アプリが実行時の役割と利用者の設定を確認します。無効化やOS側の抑制があるため、要求しただけで「表示された」と報告しないでください。アプリの送信結果もOSによる表示を保証しません。
"#.to_owned()
}
