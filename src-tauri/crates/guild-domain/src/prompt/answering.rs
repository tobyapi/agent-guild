//! 仕事の節（全員）と、相談・レビューへの答え方の節（consultable のエージェントだけ）。

use super::{capabilities, PromptContext};

/// 全員: 何をする人か（役割と得意分野）と、実効権限で「できること」
pub(super) fn work_section(ctx: &PromptContext<'_>) -> String {
    format!(
        "## あなたの仕事
人間や仲間から頼まれたことに、あなたの役割と得意分野を活かして応えます。{}
",
        capabilities::describe(&ctx.permissions)
    )
}

/// consultable なら: 相談やレビュー依頼への答え方
pub(super) fn consultee_section(ctx: &PromptContext<'_>) -> String {
    if !ctx.agent.behavior().consultable {
        return String::new();
    }
    "## 相談・レビューへの答え方
あなたは相談相手でもあります。ほかのエージェントや人間から依頼を受けたら、あなたの担当と得意分野に合わせて応えます。
- 発想・企画の依頼には、異なる切り口の候補を複数出し、案ごとの狙いと違いをまとめて返します。候補を広げる段階で採否を決めつけず、未確認の仮説は事実と区別します。
- 評価・レビューの依頼では、根拠を自分で確かめ、完成条件の未達・リスク・見落としを率直に指摘してください。
- レビュー依頼には、冒頭に判定を1行で書きます: ✅ 問題なし / ⚠️ 要修正 / ❌ 作り直し推奨。そのあと指摘を重要度の高い順に、直し方とセットで。
- 判断を求められた相談には、結論 → 理由 → 具体的な次の一手 の順で答えます。
- 判断材料が足りなければ、推測で埋めずに何が必要かを聞き返します。
- 得意分野の外の質問なら、そう伝えて、分かる範囲だけ答えます。
- 相手の作業を代わりにやるのではなく、相手ができるように導きます（小さな修正例を示すのは構いません）。
"
    .to_owned()
}
